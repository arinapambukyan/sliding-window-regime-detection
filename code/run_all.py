"""Regenerate every simulation, figure, table and number used in the paper.

    python code/run_all.py            # everything
    python code/run_all.py gauss      # only the named modules; values are merged

Writes data/*.csv, figures/*.pdf and generated/*.tex. The LaTeX source reads
numbers through \\G{key} (defined in preamble.tex from generated/numbers.tex),
so re-running this script and recompiling updates the whole paper."""
from __future__ import annotations

import json
import time

from common import VALUES_FILE, write_tex
import exp1_gauss
import exp2_kregimes
import exp1_pm1
import exp3_reflected

MODULES = {"pm1": ("Experiment I (+-1 observations)", exp1_pm1),
           "gauss": ("Experiment I (Gaussian residuals)", exp1_gauss),
           "kreg": ("Experiment II (more than two regimes)", exp2_kregimes),
           "refl": ("Experiment III (reflected walk)", exp3_reflected)}


def main(selected=None) -> None:
    """Run all experiments, or only the selected ones (their values are merged)."""
    if not selected and VALUES_FILE.exists():
        VALUES_FILE.unlink()
    for key, (name, mod) in MODULES.items():
        if selected and key not in selected:
            continue
        t0 = time.time()
        mod.run()
        print(f"{name}: done in {time.time() - t0:.0f} s")
    store = json.loads(VALUES_FILE.read_text())
    lines = ["% Generated by code/run_all.py -- do not edit by hand."]
    lines += [rf"\expandafter\def\csname gen@{k}\endcsname{{{v}}}" for k, v in sorted(store.items())]
    write_tex("numbers.tex", "\n".join(lines) + "\n")
    print(f"wrote {len(store)} values to generated/numbers.tex")


if __name__ == "__main__":
    import sys
    main(sys.argv[1:])
